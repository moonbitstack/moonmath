#!/usr/bin/env python3
"""Generate the reference values the special-function tests compare against.

Every value here comes from `mpmath` at a hundred and thirty working digits,
then rounded once to the width the test runs at: to a `Double` for the
double-precision file, and to a hundred and ten digits for the fifty- and
hundred-digit tables. `mpmath` is an independent implementation — a different
algorithm from the library's at every point — so a match is a match against other
code, not the same formula run twice.

The cases are generated once and checked in; the test run needs neither Python
nor `mpmath`, and CI does not run this script.

Usage: python scripts/gen_special.py
"""

from __future__ import annotations

import mpmath as mp
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOUBLE_TARGET = ROOT / "src" / "special" / "special_data_wbtest.mbt"
ARBITRARY_TARGET = ROOT / "src" / "special" / "generic" / "arb_data_wbtest.mbt"

mp.mp.dps = 130

