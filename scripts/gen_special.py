#!/usr/bin/env python3
"""Generate the reference values the special-function tests compare against.

The error and gamma families come from Python's `math` module, an independent
implementation in C that carries the full double precision. The elliptic
integrals come from their hypergeometric series in `decimal` at fifty digits,
and the zeta from the Euler-transformed Dirichlet eta series — both a different
algorithm from the one the library uses, so the comparison is not the same code
checking itself.

The cases are generated once and checked in, as `gen_vectors.py` does; the test
run needs neither Python nor `decimal`. CI does not run this script.

Usage: python scripts/gen_special.py
"""

from __future__ import annotations

import math
from decimal import Decimal, getcontext
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "src" / "special" / "special_data_wbtest.mbt"

getcontext().prec = 60
PI = Decimal(
    "3.14159265358979323846264338327950288419716939937510582097494"
)
TINY = Decimal(10) ** -55


def central_binomial_fraction(n: int) -> Decimal:
    """C(2n, n) / 4^n, as a Decimal."""
    numerator = Decimal(1)
    denominator = Decimal(1)
    for k in range(1, n + 1):
        numerator *= 2 * k - 1
        denominator *= 2 * k
    return numerator / denominator


def elliptic(m: float) -> tuple[Decimal, Decimal]:
    """K(m) and E(m) from their 2F1 series, at full `decimal` precision."""
    value = Decimal(m)
    k_sum = Decimal(0)
    e_sum = Decimal(1)
    coefficient = Decimal(1)
    power = Decimal(1)
    n = 0
    while n < 8000:
        term = coefficient * coefficient * power
        k_sum += term
        if n >= 1:
            e_sum -= term / Decimal(2 * n - 1)
        if abs(term) < TINY:
            break
        power *= value
        coefficient = coefficient * Decimal(2 * n + 1) / Decimal(2 * n + 2)
        n += 1
    return PI / 2 * k_sum, PI / 2 * e_sum


def zeta(s: float) -> Decimal:
    """The Riemann zeta from the Euler-transformed eta series."""
    value = Decimal(s)
    eta = Decimal(0)
    for k in range(0, 400):
        inner = Decimal(0)
        for j in range(0, k + 1):
            power = (-value * Decimal(j + 1).ln()).exp()
            inner += Decimal(-1) ** j * Decimal(math.comb(k, j)) * power
        term = inner / Decimal(2) ** (k + 1)
        eta += term
        if abs(term) < TINY:
            break
    two_to_one_minus = ((1 - value) * Decimal(2).ln()).exp()
    return eta / (1 - two_to_one_minus)


def num(x) -> str:
    """A MoonBit `Double` literal for `x`, round-trippable."""
    text = repr(float(x))
    if "e" in text or "E" in text:
        mantissa, exponent = text.lower().split("e")
        if "." not in mantissa:
            mantissa += ".0"
        return f"{mantissa}e{exponent}"
    if "." not in text:
        text += ".0"
    return text


def pairs(name: str, cases) -> str:
    lines = [f"///|", f"let {name} : Array[(Double, Double)] = ["]
    for a, b in cases:
        lines.append(f"  ({num(a)}, {num(b)}),")
    lines.append("]")
    return "\n".join(lines)


def triples(name: str, cases) -> str:
    lines = [f"///|", f"let {name} : Array[(Double, Double, Double)] = ["]
    for a, b, c in cases:
        lines.append(f"  ({num(a)}, {num(b)}, {num(c)}),")
    lines.append("]")
    return "\n".join(lines)


def main() -> None:
    erf_cases = []
    erfc_cases = []
    gamma_cases = []
    lgamma_cases = []
    for step in range(-30, 31):
        x = step * 0.1
        erf_cases.append((x, math.erf(x)))
    for step in range(0, 51):
        x = step * 0.1
        erfc_cases.append((x, math.erfc(x)))
    for x in [0.5, 0.75, 1.5, 2.5, 3.5, 4.5, 5.5, 7.5, 9.5, 0.1, -0.5, -1.5]:
        gamma_cases.append((x, math.gamma(x)))
        lgamma_cases.append((x, math.lgamma(x)))

    beta_cases = []
    for a in [0.5, 1.0, 1.5, 2.0, 3.0, 4.5]:
        for b in [0.5, 1.0, 2.0, 3.5, 5.0]:
            beta_cases.append((a, b, math.gamma(a) * math.gamma(b) / math.gamma(a + b)))

    ellipk_cases = []
    ellipe_cases = []
    for step in range(0, 18):
        m = step * 0.05
        k, e = elliptic(m)
        ellipk_cases.append((m, k))
        ellipe_cases.append((m, e))

    zeta_cases = []
    for s in [1.5, 1.75, 2.0, 2.5, 3.0, 3.5, 4.0, 5.0, 6.0, 8.0, 10.0]:
        zeta_cases.append((s, zeta(s)))

    header = (
        "// Copyright 2026 Leo Cheng\n"
        "// SPDX-License-Identifier: Apache-2.0\n"
        "\n"
        "// Generated by `scripts/gen_special.py`; do not edit.\n"
        "//\n"
        "// Each array is a list of cases: the input, the value an independent\n"
        "// implementation produced for it, and nothing else. The comparison lives in\n"
        "// `special_wbtest.mbt`.\n"
    )
    body = "\n\n".join(
        [
            pairs("erf_cases", erf_cases),
            pairs("erfc_cases", erfc_cases),
            pairs("gamma_cases", gamma_cases),
            pairs("lgamma_cases", lgamma_cases),
            triples("beta_cases", beta_cases),
            pairs("ellipk_cases", ellipk_cases),
            pairs("ellipe_cases", ellipe_cases),
            pairs("zeta_cases", zeta_cases),
        ]
    )
    TARGET.write_text(header + "\n" + body + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
