def emit_double() -> str:
    blocks = []
    for name, arity, function, points in FAMILIES:
        rows = []
        for point in points:
            arguments = point if arity > 1 else (point,)
            value = function(*[mp.mpf(str(a)) for a in arguments])
            rows.append((arguments, value))
        declared = "Double, " * arity + "Double"
        lines = ["///|", f"let {name}_cases : Array[({declared})] = ["]
        for arguments, value in rows:
            rendered = ", ".join(num(a) for a in arguments)
            lines.append(f"  ({rendered}, {num(value)}),")
        lines.append("]")
        blocks.append("\n".join(lines))
    return HEADER + "\n" + "\n\n".join(blocks) + "\n"


# The arbitrary-precision tables carry two points per family rather than the
# whole double set: each of them costs seconds at a hundred digits, and the six
# hundred double cases already cover the surface point by point.
ARB_POINTS = {
    "bessel_j": [(0.0, 1.0), (0.0, 40.0)],
    "bessel_y": [(0.0, 1.0), (0.0, 40.0)],
    "bessel_i": [(0.0, 1.0), (2.0, 8.0)],
    "bessel_k": [(0.0, 1.0), (2.0, 8.0)],
    "zeta": [2.0, -2.0],
    "erfinv": [0.5, 0.9],
    "gamma": [0.5, 10.5],
    "elliprj": [(1.0, 2.0, 3.0, 4.0)],
    "lgamma": [0.5, 10.5],
}


def emit_arbitrary_card(kind: str) -> str:
    lines = ["///|", f"let {kind}_cases : Array[(String, String, String)] = ["]
    for name, arity, function, points in FAMILIES:
        for point in ARB_POINTS.get(name, points[:2]):
            arguments = point if arity > 1 else (point,)
            value = function(*[mp.mpf(str(a)) for a in arguments])
            rendered = ",".join(str(a) for a in arguments)
            lines.append(f'  ("{name}", "{rendered}", "{text(value)}"),')
    lines.append("]")
    return "\n".join(lines)


def emit_arbitrary_file() -> str:
    blocks = [emit_arbitrary_card("fifty_digit"), emit_arbitrary_card("hundred_digit")]
    return HEADER + "\n" + "\n\n".join(blocks) + "\n"


def main() -> None:
    DOUBLE_TARGET.write_text(emit_double(), encoding="utf-8", newline="\n")
    ARBITRARY_TARGET.write_text(emit_arbitrary_file(), encoding="utf-8", newline="\n")
    print(f"wrote {DOUBLE_TARGET.relative_to(ROOT)}")
    print(f"wrote {ARBITRARY_TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
