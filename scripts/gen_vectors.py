#!/usr/bin/env python3
"""Generate the reference cases the value-by-value tests compare against.

Every operation whose result is a plain number is checked against an
independent implementation: numpy, in the same precision the package is built
in. The cases are generated once and checked in, so the test run needs neither
Python nor numpy; this script is how they came to be.

What is here is the algebra — vector arithmetic, products, matrices, quaternions,
interpolation. What is deliberately not here is anything whose point is a
convention rather than a formula: cameras, projections, Euler angles and the
intersection routines are tested against their properties and against exact
values in `shapes_wbtest.mbt`, because a second implementation of a convention
agrees with the first only if both were written the same way, which proves
nothing.

Usage: python scripts/gen_vectors.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
CASES = 24
SEED = 20261028

TARGETS = {
    "f32": (np.float32, ROOT / "src" / "vectors_data_wbtest.mbt"),
    "f64": (np.float64, ROOT / "src" / "f64" / "vectors_data_wbtest.mbt"),
}


def number(value, dtype) -> str:
    """The literal for `value`, rounded to `dtype`, short enough to read back."""
    text = np.format_float_positional(dtype(value), unique=True, trim="-")
    if "e" in text or "E" in text or "." in text:
        return text
    return text + ".0"


class Writer:
    def __init__(self, dtype):
        self.dtype = dtype
        self.lines: list[str] = []

    def num(self, value) -> str:
        return number(value, self.dtype)

    def vec(self, values, name: str) -> str:
        fields = ", ".join(self.num(v) for v in values)
        return f"{name}::new({fields})"

    def quat(self, values) -> str:
        return self.vec(values, "Quat")

    def mat(self, values, name: str) -> str:
        """A matrix from a column-major flat list."""
        fields = ", ".join(self.num(v) for v in values)
        return f"{name}::from_array([{fields}])"

    def case(self, items: tuple[str, ...]) -> None:
        self.lines.append("  (" + ", ".join(items) + "),")

    def array(self, name: str, signature: str, cases: list[tuple[str, ...]]) -> None:
        if "," in signature:
            signature = f"({signature})"
        self.lines.append("")
        self.lines.append("///|")
        self.lines.append(f"let {name} : Array[{signature}] = [")
        for case in cases:
            self.case(case)
        self.lines.append("]")

    def text(self) -> str:
        header = (
            "// Copyright 2026 Leo Cheng\n"
            "// SPDX-License-Identifier: Apache-2.0\n"
            "\n"
            "// Generated by `scripts/gen_vectors.py`; do not edit.\n"
            "//\n"
            "// Each array is a list of cases: the inputs an operation is given, the\n"
            "// result numpy computed for them in this precision, and nothing else. The\n"
            "// comparison lives in `vectors_wbtest.mbt`.\n"
        )
        return header + "\n".join(self.lines) + "\n"


def unit(rng, size):
    v = rng.uniform(-1.0, 1.0, size)
    return v / np.linalg.norm(v)


def generate(dtype) -> Writer:
    rng = np.random.default_rng(SEED)
    w = Writer(dtype)

    def pair(size):
        a = rng.uniform(-3.0, 3.0, size)
        b = rng.uniform(-3.0, 3.0, size)
        # Division by a component near zero is a different test; keep these
        # away from it.
        b = np.where(np.abs(b) < 0.25, b + 0.5, b)
        return dtype(a), dtype(b)

    for size, name in ((2, "Vec2"), (3, "Vec3"), (4, "Vec4")):
        cases = []
        for _ in range(CASES):
            a, b = pair(size)
            cases.append(
                (
                    w.vec(a, name),
                    w.vec(b, name),
                    w.vec(a + b, name),
                    w.vec(a - b, name),
                    w.vec(a * b, name),
                    w.vec(a / b, name),
                )
            )
        w.array(
            f"{name.lower()}_binary",
            f"{name}, {name}, {name}, {name}, {name}, {name}",
            cases,
        )

    for size, name in ((2, "Vec2"), (3, "Vec3"), (4, "Vec4")):
        products = []
        metrics = []
        rounding = []
        for _ in range(CASES):
            a, b = pair(size)
            products.append((w.vec(a, name), w.vec(b, name), w.num(np.dot(a, b))))
            length = np.linalg.norm(a)
            metrics.append(
                (
                    w.vec(a, name),
                    w.num(length),
                    w.num(np.dot(a, a)),
                    w.vec(a / length, name),
                )
            )
            rounding.append(
                (
                    w.vec(a, name),
                    w.vec(np.abs(a), name),
                    w.vec(np.floor(a), name),
                    w.vec(np.ceil(a), name),
                    w.vec(np.round(a), name),
                    w.vec(a - np.floor(a), name),
                )
            )
        w.array(f"{name.lower()}_dot", f"{name}, {name}, {{S}}", products)
        w.array(
            f"{name.lower()}_metrics",
            f"{name}, {{S}}, {{S}}, {name}",
            metrics,
        )
        w.array(
            f"{name.lower()}_rounding",
            f"{name}, {name}, {name}, {name}, {name}, {name}",
            rounding,
        )

    lerps = []
    for _ in range(CASES):
        a, b = pair(3)
        t = dtype(rng.uniform(-0.5, 1.5))
        lerps.append((w.vec(a, "Vec3"), w.vec(b, "Vec3"), w.num(t), w.vec(a + (b - a) * t, "Vec3")))
    w.array("vec3_lerp", "Vec3, Vec3, {S}, Vec3", lerps)

    crosses = []
    angles = []
    projections = []
    reflections = []
    for _ in range(CASES):
        a, b = pair(3)
        crosses.append((w.vec(a, "Vec3"), w.vec(b, "Vec3"), w.vec(np.cross(a, b), "Vec3")))
        cosine = dtype(
            np.clip(
                np.dot(a / np.linalg.norm(a), b / np.linalg.norm(b)), -1.0, 1.0
            )
        )
        angles.append(
            (w.vec(a, "Vec3"), w.vec(b, "Vec3"), w.num(np.arccos(cosine)))
        )
        scale = dtype(np.dot(a, b) / np.dot(b, b))
        projections.append(
            (
                w.vec(a, "Vec3"),
                w.vec(b, "Vec3"),
                w.vec(b * scale, "Vec3"),
                w.vec(a - b * scale, "Vec3"),
            )
        )
        normal = unit(rng, 3).astype(dtype)
        incident = unit(rng, 3).astype(dtype)
        reflected = incident - 2.0 * np.dot(incident, normal) * normal
        reflections.append(
            (w.vec(incident, "Vec3"), w.vec(normal, "Vec3"), w.vec(reflected, "Vec3"))
        )
    w.array("vec3_cross", "Vec3, Vec3, Vec3", crosses)
    w.array("vec3_angle", "Vec3, Vec3, {S}", angles)
    w.array("vec3_projection", "Vec3, Vec3, Vec3, Vec3", projections)
    w.array("vec3_reflection", "Vec3, Vec3, Vec3", reflections)

    flat = []
    for _ in range(CASES):
        a, b = pair(2)
        flat.append(
            (
                w.vec(a, "Vec2"),
                w.vec(b, "Vec2"),
                w.num(a[0] * b[1] - a[1] * b[0]),
                w.num(np.arctan2(a[0] * b[1] - a[1] * b[0], np.dot(a, b))),
            )
        )
    w.array("vec2_cross", "Vec2, Vec2, {S}, {S}", flat)

    for size, name in ((2, "Mat2"), (3, "Mat3"), (4, "Mat4")):
        products = []
        resolved = []
        for _ in range(CASES):
            a = rng.uniform(-2.0, 2.0, (size, size)).astype(dtype)
            b = rng.uniform(-2.0, 2.0, (size, size)).astype(dtype)
            products.append(
                (
                    w.mat(a.flatten("F"), name),
                    w.mat(b.flatten("F"), name),
                    w.mat((a @ b).flatten("F"), name),
                    w.num(np.max(np.abs(a) @ np.abs(b))),
                )
            )
            vector = dtype(rng.uniform(-2.0, 2.0, size))
            resolved.append(
                (
                    w.mat(a.flatten("F"), name),
                    w.vec(vector, f"Vec{size}"),
                    w.vec(a @ vector, f"Vec{size}"),
                    w.num(np.max(np.abs(a) @ np.abs(vector))),
                )
            )
        w.array(
            f"{name.lower()}_product", f"{name}, {name}, {name}, {{S}}", products
        )
        w.array(
            f"{name.lower()}_vector", f"{name}, Vec{size}, Vec{size}, {{S}}", resolved
        )

        transposes = []
        determinants = []
        inverses = []
        for _ in range(CASES):
            a = rng.uniform(-2.0, 2.0, (size, size)).astype(dtype)
            if abs(np.linalg.det(a)) < 0.2:
                # Keep the generic cases away from singular ones; those have
                # their own test.
                a = a + np.eye(size, dtype=dtype)
            transposes.append((w.mat(a.flatten("F"), name), w.mat(a.T.flatten("F"), name),))
            determinants.append((w.mat(a.flatten("F"), name), w.num(np.linalg.det(a))))
            inverses.append(
                (
                    w.mat(a.flatten("F"), name),
                    w.mat(np.linalg.inv(a.astype(np.float64)).astype(dtype).flatten("F"), name),
                )
            )
        w.array(f"{name.lower()}_transpose", f"{name}, {name}", transposes)
        w.array(f"{name.lower()}_determinant", f"{name}, {{S}}", determinants)
        w.array(f"{name.lower()}_inverse", f"{name}, {name}", inverses)

    axis_angles = []
    rotations = []
    matrices = []
    for _ in range(CASES):
        axis = unit(rng, 3).astype(dtype)
        angle = dtype(rng.uniform(-3.0, 3.0))
        half = angle / dtype(2.0)
        quat = np.array(
            [*(axis * np.sin(half)), np.cos(half)], dtype=dtype
        )
        axis_angles.append(
            (w.vec(axis, "Vec3"), w.num(angle), w.quat(quat))
        )
        vector = dtype(rng.uniform(-2.0, 2.0, 3))
        axis_part = quat[:3]
        t = 2.0 * np.cross(axis_part, vector)
        turned = vector + quat[3] * t + np.cross(axis_part, t)
        rotations.append(
            (w.quat(quat), w.vec(vector, "Vec3"), w.vec(turned, "Vec3"))
        )
        x, y, z, wq = quat
        matrix = np.array(
            [
                [1 - 2 * (y * y + z * z), 2 * (x * y - wq * z), 2 * (x * z + wq * y)],
                [2 * (x * y + wq * z), 1 - 2 * (x * x + z * z), 2 * (y * z - wq * x)],
                [2 * (x * z - wq * y), 2 * (y * z + wq * x), 1 - 2 * (x * x + y * y)],
            ],
            dtype=dtype,
        )
        matrices.append((w.quat(quat), w.mat(matrix.flatten("F"), "Mat3")))
    w.array("quat_axis_angle", "Vec3, {S}, Quat", axis_angles)
    w.array("quat_rotation", "Quat, Vec3, Vec3", rotations)
    w.array("quat_matrix", "Quat, Mat3", matrices)

    slerps = []
    for _ in range(CASES):
        first = unit(rng, 4).astype(dtype)
        second = unit(rng, 4).astype(dtype)
        t = dtype(rng.uniform(0.0, 1.0))
        cosine = float(np.dot(first, second))
        if cosine < 0.0:
            second = -second
            cosine = -cosine
        angle = np.arccos(min(cosine, 1.0))
        sine = np.sin(angle)
        a = np.sin((1.0 - t) * angle) / sine
        b = np.sin(t * angle) / sine
        mixed = a * first + b * second
        slerps.append(
            (
                w.quat(first),
                w.quat(second),
                w.num(t),
                w.quat(mixed),
            )
        )
    w.array("quat_slerp", "Quat, Quat, {S}, Quat", slerps)

    arcs = []
    for _ in range(CASES):
        start = unit(rng, 3).astype(dtype)
        finish = unit(rng, 3).astype(dtype)
        cosine = float(np.dot(start, finish))
        axis = np.cross(start, finish)
        length = np.linalg.norm(axis)
        if length < 1e-6:
            continue
        angle = np.arctan2(length, cosine)
        half = angle / 2.0
        quat = np.array(
            [*(axis / length * np.sin(half)), np.cos(half)], dtype=dtype
        )
        arcs.append((w.vec(start, "Vec3"), w.vec(finish, "Vec3"), w.quat(quat)))
    w.array("quat_arc", "Vec3, Vec3, Quat", arcs)

    affines = []
    for _ in range(CASES):
        linear = rng.uniform(-1.5, 1.5, (3, 3)).astype(dtype)
        if abs(np.linalg.det(linear)) < 0.3:
            linear = linear + np.eye(3, dtype=dtype)
        offset = dtype(rng.uniform(-3.0, 3.0, 3))
        point = dtype(rng.uniform(-3.0, 3.0, 3))
        affines.append(
            (
                w.mat(linear.flatten("F"), "Mat3"),
                w.vec(offset, "Vec3"),
                w.vec(point, "Vec3"),
                w.vec(linear @ point + offset, "Vec3"),
                w.vec(linear @ point, "Vec3"),
                w.num(np.max((np.abs(linear) @ np.abs(point)) + np.abs(offset))),
            )
        )
    w.array(
        "affine3_apply",
        "Mat3, Vec3, Vec3, Vec3, Vec3, {S}",
        affines,
    )
    return w


def main() -> None:
    for precision, (dtype, path) in TARGETS.items():
        writer = generate(dtype)
        text = writer.text().replace("{S}", "Float" if precision == "f32" else "Double")
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
